<?php

declare(strict_types=1);

namespace RageKit\Cli\Dev;

use RageKit\Cli\Project\GeneratedFile;

/**
 * The file `php` runs in dev mode: a class-map autoloader over the PHP files tpc would compile
 * (plain PHP needs a parent class loaded before its child), the files that declare functions,
 * then the app's main().
 */
final class Bootstrap
{
    /**
     * @param list<string> $phpFiles   every PHP file of the app, RageKit core and the dev runtime
     * @param list<string> $eagerFiles files to require up front (they declare functions)
     */
    public static function write(string $file, array $phpFiles, array $eagerFiles): void
    {
        $map = '';
        foreach (self::classes($phpFiles) as $class => $path) {
            $map .= '        ' . var_export($class, true) . ' => ' . var_export($path, true) . ",\n";
        }
        $requires = '';
        foreach ($eagerFiles as $path) {
            $requires .= 'require ' . var_export($path, true) . ";\n";
        }
        GeneratedFile::write($file, "<?php\n\n// Generated by ragekit dev. Do not edit.\n\n"
            . "spl_autoload_register(static function (string \$class): void {\n"
            . "    static \$map = [\n$map    ];\n"
            . "    if (isset(\$map[\$class])) {\n        require \$map[\$class];\n    }\n});\n\n"
            . $requires . "\nmain();\n");
    }

    /**
     * @param list<string> $files
     * @return array<string, string> class, interface, trait or enum => file declaring it
     */
    public static function classes(array $files): array
    {
        $classes = [];
        foreach ($files as $file) {
            $tokens = token_get_all((string) file_get_contents($file));
            $namespace = '';
            $count = count($tokens);
            for ($i = 0; $i < $count; $i++) {
                $token = $tokens[$i];
                if (!is_array($token)) {
                    continue;
                }
                if ($token[0] === T_NAMESPACE) {
                    $namespace = '';
                    for ($j = $i + 1; $j < $count && $tokens[$j] !== ';' && $tokens[$j] !== '{'; $j++) {
                        if (is_array($tokens[$j]) && in_array($tokens[$j][0], [T_NAME_QUALIFIED, T_STRING], true)) {
                            $namespace .= $tokens[$j][1];
                        }
                    }
                    continue;
                }
                if (!in_array($token[0], [T_CLASS, T_INTERFACE, T_TRAIT, T_ENUM], true)) {
                    continue;
                }
                $previous = self::significant($tokens, $i, -1);
                if ($previous !== null && is_array($previous) && in_array($previous[0], [T_DOUBLE_COLON, T_NEW], true)) {
                    continue; // Foo::class, new class {}
                }
                $name = self::significant($tokens, $i, 1);
                if (is_array($name) && $name[0] === T_STRING) {
                    $classes[($namespace === '' ? '' : "$namespace\\") . $name[1]] = $file;
                }
            }
        }
        return $classes;
    }

    /** The nearest token before ($step -1) or after ($step 1) $i that isn't whitespace or a comment. */
    private static function significant(array $tokens, int $i, int $step): mixed
    {
        for ($j = $i + $step; $j >= 0 && $j < count($tokens); $j += $step) {
            if (is_array($tokens[$j]) && in_array($tokens[$j][0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) {
                continue;
            }
            return $tokens[$j];
        }
        return null;
    }
}
