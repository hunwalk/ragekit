<?php

declare(strict_types=1);

namespace RageKit\Cli\Modules;

/**
 * Everything RageKit generates from a module.yml:
 *  - header():       rk_module_<name>.h, the C ABI the module's library implements;
 *  - callEntry():    rk_module_<name>_call.cc, compiled into the library: call any function by
 *                    name with text arguments (the dev shell's single entry point);
 *  - stub(), host(): the PHP functions and their C++17 PHPX host for release builds, which find
 *                    the library at runtime through libragekit_slint;
 *  - devFunctions(): the same PHP functions for `ragekit dev`, calling over the dev protocol.
 */
final class ModuleEmitter
{
    private const C = ['int' => 'int64_t', 'float' => 'double', 'bool' => 'int', 'string' => 'const char *'];
    private const PHPX = ['int' => 'Int', 'float' => 'Float', 'bool' => 'Bool', 'string' => 'String'];

    public static function header(Module $m): string
    {
        $out = "// Generated by ragekit from module.yml ({$m->name}). Do not edit.\n"
            . "// The C ABI the {$m->name} module's library implements.\n#pragma once\n\n#include \"ragekit_module.h\"\n\n"
            . "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n";
        foreach ($m->functions as $fn) {
            $out .= 'RKM_API ' . self::cReturn($fn->returns) . "rkm_{$fn->name}(" . self::cParams($fn) . ");\n";
        }
        $out .= "\n/** Called once before any function, with the callback that sends events to PHP. */\n"
            . "RKM_API void rkm_{$m->name}_init(rk_post_fn post);\n"
            . "/** Frees everything (handles become invalid); called when PHP restarts in dev mode. */\n"
            . "RKM_API void rkm_{$m->name}_reset(void);\n"
            . "/** Generated (rk_module_{$m->name}_call.cc): calls a function by name with text arguments. */\n"
            . "RKM_API const char *rkm_{$m->name}_call(const char *function, const char *const *args, const size_t *lens, size_t count, int *ok);\n\n"
            . "#ifdef __cplusplus\n}\n#endif\n";
        return $out;
    }

    public static function callEntry(Module $m): string
    {
        $cases = '';
        foreach ($m->functions as $fn) {
            $n = count($fn->params);
            $prepare = '';
            $args = [];
            $i = 0;
            foreach ($fn->params as $name => $type) {
                $prepare .= "        const std::string a$i(args[$i], lens[$i]);\n";
                $args[] = match ($type) {
                    'int' => "std::strtoll(a$i.c_str(), nullptr, 10)",
                    'float' => "std::strtod(a$i.c_str(), nullptr)",
                    'bool' => "a$i == \"1\" ? 1 : 0",
                    default => "a$i.data(), a$i.size()",
                };
                $i++;
            }
            $call = "rkm_{$fn->name}(" . implode(', ', $args) . ')';
            $result = match ($fn->returns) {
                null => "        $call;\n        out.clear();\n",
                'int' => "        out = std::to_string($call);\n",
                'float' => "        out = number($call);\n",
                'bool' => "        out = $call ? \"1\" : \"0\";\n",
                // A NULL string result (the module broke its contract) reads as "".
                default => "        const char *result = $call;\n        out = result != nullptr ? result : \"\";\n",
            };
            $cases .= "    if (fn == \"{$fn->name}\") {\n"
                . "        if (count != $n) {\n            return fail(ok, \"{$fn->name} takes $n argument" . ($n === 1 ? '' : 's') . ", got \" + std::to_string(count));\n        }\n"
                . $prepare . $result . "        return out.c_str();\n    }\n";
        }
        return "// Generated by ragekit from module.yml ({$m->name}). Do not edit.\n"
            . "// Calls a function of the {$m->name} module by name, arguments and result as text.\n"
            . "#include \"rk_module_{$m->name}.h\"\n\n#include <charconv>\n#include <cstdlib>\n#include <string>\n\n"
            . "namespace {\n\nthread_local std::string out;\n\n"
            . "const char *fail(int *ok, std::string message)\n{\n    *ok = 0;\n    out = std::move(message);\n    return out.c_str();\n}\n\n"
            . "// Shortest text that reads back as the same double.\nstd::string number(double value)\n{\n    char buffer[64];\n"
            . "    auto end = std::to_chars(buffer, buffer + sizeof buffer, value).ptr;\n    return std::string(buffer, end);\n}\n\n} // namespace\n\n"
            . "extern \"C\" RKM_API const char *rkm_{$m->name}_call(const char *function, const char *const *args, const size_t *lens, size_t count, int *ok)\n{\n"
            . "    *ok = 1;\n    const std::string fn(function);\n"
            . $cases
            . "    return fail(ok, \"unknown function \" + fn);\n}\n";
    }

    public static function stub(Module $m): string
    {
        $out = "<?php\n\n// Generated by ragekit from module.yml ({$m->name}). Do not edit.\n"
            . "// Implemented by {$m->name}_host.cc, which finds the module's library at runtime.\n\n";
        foreach ($m->functions as $fn) {
            $out .= 'function ' . self::phpSignature($fn) . " {}\n\n";
        }
        return $out;
    }

    public static function host(Module $m): string
    {
        $out = "// Generated by ragekit from module.yml ({$m->name}). Do not edit.\n"
            . "// PHP side of the {$m->name} module (C++17, compiled by TypePHP). The library is found at runtime\n"
            . "// through libragekit_slint; a missing library or function returns the type's default.\n"
            . "#include <phpx.h>\n\n#include \"ragekit_slint.h\"\n#include \"rk_module_{$m->name}.h\"\n\nusing namespace php;\n\n"
            . "namespace {\n\n"
            . "// A library lacking any of these counts as unavailable (Modules::available() is false).\n"
            . "[[maybe_unused]] const bool expected = (rk_module_expect(\"{$m->name}\", \"" . implode('\\n', array_map(fn($f) => "rkm_$f", array_keys($m->functions))) . "\"), true);\n\n"
            . "void *rkm_symbol(const char *name)\n{\n    static int64_t module = -1;\n    if (module == -1) {\n"
            . "        module = rk_module_open(\"{$m->name}\");\n        if (module != 0) {\n"
            . "            if (auto init = reinterpret_cast<decltype(&rkm_{$m->name}_init)>(rk_module_symbol(module, \"rkm_{$m->name}_init\"))) {\n"
            . "                init(rk_post_event);\n            }\n        }\n    }\n"
            . "    return module == 0 ? nullptr : rk_module_symbol(module, name);\n}\n\n} // namespace\n";
        foreach ($m->functions as $fn) {
            $params = [];
            $args = [];
            foreach ($fn->params as $name => $type) {
                $params[] = self::PHPX[$type] . " $name";
                $args[] = match ($type) {
                    'string' => "$name.data(), $name.length()",
                    'bool' => "$name ? 1 : 0",
                    default => $name,
                };
            }
            $ret = $fn->returns === null ? 'void' : self::PHPX[$fn->returns];
            $default = match ($fn->returns) {
                null => 'return;',
                'int' => 'return 0;',
                'float' => 'return 0.0;',
                'bool' => 'return false;',
                default => 'return String("");',
            };
            $call = 'fn(' . implode(', ', $args) . ')';
            $body = match ($fn->returns) {
                null => "    $call;\n",
                'bool' => "    return $call != 0;\n",
                'string' => "    const char *result = $call;\n    return String(result != nullptr ? result : \"\");\n",
                default => "    return $call;\n",
            };
            $out .= "\n$ret php_{$fn->name}(" . implode(', ', $params) . ")\n{\n"
                . "    static auto fn = reinterpret_cast<decltype(&rkm_{$fn->name})>(rkm_symbol(\"rkm_{$fn->name}\"));\n"
                . "    if (fn == nullptr) {\n        $default\n    }\n" . $body . "}\n";
        }
        return $out;
    }

    public static function devFunctions(Module $m): string
    {
        $out = "<?php\n\n// Generated by ragekit from module.yml ({$m->name}). Do not edit.\n"
            . "// `ragekit dev`: the {$m->name} module's functions, called in the dev shell.\n";
        foreach ($m->functions as $fn) {
            $args = [];
            foreach ($fn->params as $name => $type) {
                $args[] = match ($type) {
                    'int' => "(string) \$$name",
                    'float' => "var_export(\$$name, true)",
                    'bool' => "\$$name ? '1' : '0'",
                    default => "\$$name",
                };
            }
            $call = "\\RageKit\\Slint\\Dev\\Session::call('{$fn->name}', [" . implode(', ', $args) . '])';
            $body = match ($fn->returns) {
                null => "    $call;\n",
                'int' => "    return (int) $call;\n",
                'float' => "    return (float) $call;\n",
                'bool' => "    return $call === '1';\n",
                default => "    return $call;\n",
            };
            $out .= "\nfunction " . self::phpSignature($fn) . "\n{\n$body}\n";
        }
        return $out;
    }

    private static function phpSignature(ModuleFunction $fn): string
    {
        $params = [];
        foreach ($fn->params as $name => $type) {
            $params[] = "$type \$$name";
        }
        return "{$fn->name}(" . implode(', ', $params) . '): ' . ($fn->returns ?? 'void');
    }

    private static function cReturn(?string $type): string
    {
        return $type === null ? 'void ' : (self::C[$type] === 'const char *' ? 'const char *' : self::C[$type] . ' ');
    }

    private static function cParams(ModuleFunction $fn): string
    {
        $params = [];
        foreach ($fn->params as $name => $type) {
            $params[] = $type === 'string' ? "const char *$name, size_t {$name}_len" : self::C[$type] . " $name";
        }
        return $params === [] ? 'void' : implode(', ', $params);
    }
}
