<?php

declare(strict_types=1);

namespace RageKit\Cli\Slint;

/**
 * RageKit\Generated\Screens: statically typed PHP that reads each screen's shown values and runs
 * its actions — no dynamic property access, so TypePHP (and Nano) compile it directly.
 */
final class BinderEmitter
{
    /** @param list<ScreenModel> $screens */
    public static function emit(array $screens): string
    {
        $name = $values = $dispatch = $helpers = '';
        foreach ($screens as $screen) {
            $class = '\\' . $screen->class->name;
            $short = $screen->class->short;
            $name .= "        if (\$screen instanceof $class) {\n            return '$short';\n        }\n";
            $values .= "        if (\$screen instanceof $class) {\n            return self::values$short(\$screen);\n        }\n";
            $dispatch .= "        if (\$screen instanceof $class) {\n            return self::dispatch$short(\$screen, \$action, \$arg);\n        }\n";
            $helpers .= self::valuesMethod($screen) . self::dispatchMethod($screen);
        }
        return "<?php\n\n// Generated by ragekit from .rk templates. Do not edit.\n\n"
            . "namespace RageKit\\Generated;\n\nuse RageKit\\Screen;\n\n"
            . "/** Each Screen's compiled Slint component: shown values, and actions → handlers. */\n"
            . "final class Screens\n{\n"
            . "    public static function name(Screen \$screen): string\n    {\n$name"
            . "        throw new \\RuntimeException('No compiled template for ' . \\get_class(\$screen));\n    }\n\n"
            . "    /** @return array<int, mixed> property id => current value */\n"
            . "    public static function values(Screen \$screen): array\n    {\n{$values}        return [];\n    }\n\n"
            . "    /** Runs an action; returns the id of a property the UI already shows (two-way input), else 0. */\n"
            . "    public static function dispatch(Screen \$screen, int \$action, string \$arg): int\n    {\n{$dispatch}        return 0;\n    }\n\n"
            . $helpers
            . "    /** @return list<string> */\n"
            . "    private static function strings(array \$items): array\n    {\n"
            . "        \$out = [];\n        foreach (\$items as \$item) {\n            \$out[] = (string) \$item;\n        }\n        return \$out;\n    }\n}\n";
    }

    private static function valuesMethod(ScreenModel $screen): string
    {
        $entries = '';
        foreach ($screen->bindings as $binding) {
            $read = $binding->source === 'method' ? "\$s->{$binding->name}()" : "\$s->{$binding->name}";
            if ($binding->type === 'list') {
                $read = "self::strings($read)";
            }
            $entries .= "            {$binding->id} => $read,\n";
        }
        return "    /** @return array<int, mixed> */\n"
            . "    private static function values{$screen->class->short}(\\{$screen->class->name} \$s): array\n    {\n"
            . "        return [\n$entries        ];\n    }\n\n";
    }

    private static function dispatchMethod(ScreenModel $screen): string
    {
        $cases = '';
        foreach ($screen->actions as $action) {
            if ($action->kind === 'set') {
                $cases .= "            case {$action->id}:\n"
                    . "                \$s->{$action->target} = " . self::convert('$arg', $action->binding->type) . ";\n"
                    . "                return {$action->binding->id};\n";
                continue;
            }
            $params = $screen->class->handlers[$action->target] ?? [];
            $args = [];
            foreach ($action->args as $i => [$kind, $value]) {
                $args[] = $kind === 'arg'
                    ? self::convert('$arg', $params[$i] ?? 'string')
                    : self::literal((string) $value, $params[$i] ?? 'string');
            }
            $cases .= "            case {$action->id}:\n"
                . "                \$s->{$action->target}(" . implode(', ', $args) . ");\n"
                . "                return 0;\n";
        }
        return "    private static function dispatch{$screen->class->short}(\\{$screen->class->name} \$s, int \$action, string \$arg): int\n    {\n"
            . "        switch (\$action) {\n$cases            default:\n                return 0;\n        }\n    }\n\n";
    }

    /** A template's quoted literal as a PHP literal of the parameter's type, converted at build time. */
    private static function literal(string $value, string $type): string
    {
        return match (ltrim($type, '?')) {
            'bool' => in_array(strtolower($value), ['true', '1'], true) ? 'true' : 'false',
            'int' => (string) (int) $value,
            'float' => self::floatLiteral((float) $value),
            default => var_export($value, true),
        };
    }

    private static function floatLiteral(float $value): string
    {
        $text = var_export($value, true);
        return str_contains($text, '.') || str_contains($text, 'E') || str_contains($text, 'N') || str_contains($text, 'I') ? $text : $text . '.0';
    }

    private static function convert(string $expression, string $type): string
    {
        return match (ltrim($type, '?')) {
            'int' => "(int) $expression",
            'float' => "(float) $expression",
            'bool' => "$expression === '1'",
            default => $expression,
        };
    }
}
