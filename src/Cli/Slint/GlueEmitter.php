<?php

declare(strict_types=1);

namespace RageKit\Cli\Slint;

/**
 * views_glue.cc: one rk::Instance per screen (C++20, compiled into the bridge library), mapping
 * property ids to the setters slint-compiler generated in app.h.
 */
final class GlueEmitter
{
    private const SETTERS = [
        'string' => 'set_string(int id, std::string_view value)',
        'int' => 'set_int(int id, int64_t value)',
        'float' => 'set_float(int id, double value)',
        'bool' => 'set_bool(int id, bool value)',
        'list' => 'set_list(int id, std::vector<slint::SharedString> value)',
    ];

    /** @param list<ScreenModel> $screens */
    public static function emit(array $screens): string
    {
        $code = "// Generated by ragekit from .rk templates. Do not edit.\n"
            . "#include \"rk_instance.h\"\n#include \"app.h\"\n\n"
            . "#include <memory>\n#include <string_view>\n#include <utility>\n#include <vector>\n\n"
            . "namespace {\n\n";
        foreach ($screens as $screen) {
            $code .= self::instance($screen);
        }
        $code .= "} // namespace\n\n"
            . "std::unique_ptr<rk::Instance> rk::create_instance(std::string_view screen, int64_t window)\n{\n";
        foreach ($screens as $screen) {
            $name = $screen->class->short;
            $code .= "    if (screen == \"$name\") {\n        return std::make_unique<{$name}Instance>(window);\n    }\n";
        }
        return $code . "    return nullptr;\n}\n";
    }

    private static function instance(ScreenModel $screen): string
    {
        $name = $screen->class->short;
        $cases = array_fill_keys(array_keys(self::SETTERS), '');
        // Slint's `int` is 32-bit and `float` is f32, so the bridge's int64/double narrow here.
        foreach ($screen->bindings as $binding) {
            $setter = 'handle_->set_' . $binding->slintName();
            $cases[$binding->type] .= match ($binding->type) {
                'string' => "        case {$binding->id}: $setter(slint::SharedString(value)); break;\n",
                'int' => "        case {$binding->id}: $setter(static_cast<int>(value)); break;\n",
                'float' => "        case {$binding->id}: $setter(static_cast<float>(value)); break;\n",
                'bool' => "        case {$binding->id}: $setter(value); break;\n",
                'list' => "        case {$binding->id}: $setter(std::make_shared<slint::VectorModel<slint::SharedString>>(std::move(value))); break;\n",
            };
        }
        $methods = '';
        foreach (self::SETTERS as $type => $signature) {
            $methods .= "    void $signature override\n    {\n        switch (id) {\n{$cases[$type]}        default: break;\n        }\n    }\n";
        }
        return "class {$name}Instance final : public rk::Instance {\npublic:\n"
            . "    explicit {$name}Instance(int64_t window) : handle_({$name}::create())\n    {\n"
            . "        handle_->on_action([window](int action, slint::SharedString arg) {\n"
            . "            rk::emit_action(window, action, std::string_view(arg));\n        });\n"
            . "        handle_->window().on_close_requested([window] {\n"
            . "            rk::emit_close(window);\n"
            . "            return slint::CloseRequestResponse::KeepWindowShown;\n        });\n    }\n"
            . "    slint::Window &window() override { return handle_->window(); }\n"
            . "    void show() override { handle_->show(); }\n"
            . "    void hide() override { handle_->hide(); }\n"
            . "    void set_title(std::string_view value) override { handle_->set_rk_title(slint::SharedString(value)); }\n"
            . $methods
            . "\nprivate:\n    slint::ComponentHandle<{$name}> handle_;\n};\n\n";
    }
}
